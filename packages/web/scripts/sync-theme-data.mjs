// Generates src/core/theme/data.generated.ts from design/dist/tokens.resolved.json: the token values and
// alias table the TypeScript ThemeBuilder needs (mirrors SlateTokens.Values / Themes.*.Values / Aliases).
// `--check` exits 1 when the file is stale. Run after `slate-tokens build`.
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const source = resolve(root, '../../design/dist/tokens.resolved.json');
const target = resolve(root, 'src/core/theme/data.generated.ts');

const tokens = JSON.parse(readFileSync(source, 'utf8'));
const pairs = (section, pick) =>
  Object.entries(section)
    .filter(([, t]) => t.type !== 'Typography' && pick(t))
    .map(([path, t]) => [path, pick(t)]);

const fmt = (list) => '[\n' + list.map(([a, b]) => `  [${JSON.stringify(a)}, ${JSON.stringify(b)}],`).join('\n') + '\n]';

const content = `// Generated by scripts/sync-theme-data.mjs from design/dist/tokens.resolved.json. Do not edit.
/* eslint-disable */

export type TokenPairs = ReadonlyArray<readonly [string, string]>;

/** Every shared token by path, as a CSS value (typography excluded). Mirrors SlateTokens.Values. */
export const sharedValues: TokenPairs = ${fmt(pairs(tokens.shared, (t) => t.value))};

/** Every themed token by path. Mirrors SlateTokens.Themes.Light/Dark.Values. */
export const themeValues: Readonly<Record<'light' | 'dark', TokenPairs>> = {
  light: ${fmt(pairs(tokens.themes.light, (t) => t.value))},
  dark: ${fmt(pairs(tokens.themes.dark, (t) => t.value))},
};

/** Token path → the token it aliases. Mirrors SlateTokens.Themes.Light/Dark.Aliases. */
export const themeAliases: Readonly<Record<'light' | 'dark', TokenPairs>> = {
  light: ${fmt(pairs(tokens.themes.light, (t) => t.aliasOf))},
  dark: ${fmt(pairs(tokens.themes.dark, (t) => t.aliasOf))},
};
`;

if (process.argv.includes('--check')) {
  const current = existsSync(target) ? readFileSync(target, 'utf8') : '';
  if (current !== content) {
    console.error('src/core/theme/data.generated.ts is stale — run: npm run sync:theme -w @slate/web');
    process.exit(1);
  }
  console.log('theme data up to date');
} else {
  writeFileSync(target, content);
  console.log('wrote src/core/theme/data.generated.ts');
}
